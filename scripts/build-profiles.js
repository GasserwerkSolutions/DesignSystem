#!/usr/bin/env node

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const esbuild = require("esbuild");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "dist", "profiles");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "manifest", "builder-profile.json"), "utf8"));
const entry = path.join(ROOT, manifest.entry);

function build(outfile, minify) {
  esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    minify,
    outfile,
    loader: { ".css": "css" },
    logLevel: "silent",
    legalComments: "none",
  });
}

fs.mkdirSync(OUT, { recursive: true });
const readableFile = path.join(OUT, "builder.css");
const minifiedFile = path.join(OUT, "builder.min.css");
build(readableFile, false);
build(minifiedFile, true);

const css = fs.readFileSync(minifiedFile, "utf8");
const sha256 = crypto.createHash("sha256").update(css).digest("hex");
const artifact = {
  version: pkg.version,
  profile: {
    id: manifest.id,
    sha256,
    css,
    manifest,
  },
};
const wrapper = `/* Generated by scripts/build-profiles.js. Do not edit. */\n` +
  `(function(root){root.GasserwerkDesignSystem=${JSON.stringify(artifact)};})(typeof window!=="undefined"?window:globalThis);\n`;
fs.writeFileSync(path.join(OUT, "builder-profile.js"), wrapper);

console.log(`[profiles] ${manifest.id}@${pkg.version}`);
console.log(`  CSS: ${(Buffer.byteLength(css) / 1024).toFixed(1)} KB minified`);
console.log(`  SHA-256: ${sha256}`);
